"""`node_modules` is ignored as a link as well as a directory.

A worktree links its dependencies from the main checkout rather than
installing them, and git sees a symbolic link as a file -- so a trailing-slash
pattern, which matches directories only, does not reach it and `git add -A`
stages the link.
"""

from __future__ import annotations

import subprocess

from tests._repo import REPO_ROOT


def check_ignore(path: str) -> subprocess.CompletedProcess[str]:
    """What git says about `path`, asked without the working tree or the index.

    `--no-index` is what lets this ask about a path that need not exist, which
    is how a file-shaped `node_modules` is asked about from a checkout where it
    happens to be a directory.
    """
    return subprocess.run(
        ["git", "check-ignore", "-v", "--no-index", path],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def test_a_node_modules_that_is_not_a_directory_is_ignored() -> None:
    """The case a worktree creates, and the one a trailing slash misses."""
    done = check_ignore("node_modules")
    assert done.returncode == 0, (
        "git does not ignore a non-directory `node_modules`, so a worktree's linked "
        "node_modules is staged by `git add -A` and the commit carries a link to an "
        f"absolute path on one machine. `git check-ignore` said: {done.stdout or done.stderr!r}"
    )


def test_it_is_ignored_below_the_root_too() -> None:
    """`ui/node_modules` is the second link the worktree recipe makes."""
    done = check_ignore("ui/node_modules")
    assert done.returncode == 0, (
        "`ui/node_modules` is not ignored, and the worktree recipe in CLAUDE.md links "
        f"it. `git check-ignore` said: {done.stdout or done.stderr!r}"
    )
