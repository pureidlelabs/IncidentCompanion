/**
 * What is *in* each demo case. Generated - with one exception, below.
 *
 * A row names another by a local key, resolved to a uuid at seed time; a key
 * naming nothing throws. Times are minute offsets from the case's start.
 * Report prose is markdown, which the seeder turns into the CRDT nodes an
 * analyst's editor would have produced.
 *
 * **This file is written by hand, and there is no generator to re-run.** Edit
 * it directly; nothing else produces it and nothing has to be kept in step
 * with it.
 */

export interface DemoContent {
  readonly reference: string
  /** How each finding was obtained. Seeded first: most collections cite one. */
  readonly methods?: Record<string, Record<string, unknown>>
  readonly systems?: Record<string, Record<string, unknown>>
  readonly accounts?: Record<string, Record<string, unknown>>
  readonly malware?: Record<string, Record<string, unknown>>
  readonly networkIndicators?: Record<string, Record<string, unknown>>
  readonly cloudApps?: Record<string, Record<string, unknown>>
  readonly evidence?: Record<string, Record<string, unknown>>
  /** Cites evidence, so it is seeded after it. */
  readonly impact?: Record<string, Record<string, unknown>>
  readonly actions?: Record<string, Record<string, unknown>>
  readonly caseNotes?: Record<string, Record<string, unknown>>
  /** Ordered; `atMinute` is the offset from the case's start. */
  readonly timeline?: readonly ({ atMinute: number } & Record<string, unknown>)[]
  readonly reports?: readonly DemoReport[]
}

/** One section of a demo report. `body` is markdown, and only a written block has one. */
export interface DemoReportBlock {
  readonly kind: string
  readonly headingKey?: string
  /** The analyst's own title, where they gave one instead of taking the key's. */
  readonly heading?: string
  readonly body?: string
}

/**
 * A report a demo case ships with.
 *
 * **`sentAtMinute` makes it a filed document**, which is the state worth
 * demonstrating: a sent report is frozen and every export paints the tree that
 * was frozen rather than re-resolving the case, so a demo with none never shows
 * that half of the lifecycle.
 */
export interface DemoReport {
  readonly label: string
  /** The layout it was seeded from, by the library name. */
  readonly template: string
  readonly tlp?: string
  readonly stage?: string
  readonly language?: string
  readonly status?: string
  readonly createdAtMinute: number
  readonly sentAtMinute?: number
  readonly blocks: readonly DemoReportBlock[]
}

