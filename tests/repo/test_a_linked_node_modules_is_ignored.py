"""`node_modules` is ignored as a link as well as a directory.

A worktree links its dependencies from the main checkout rather than
installing them, and a symbolic link is a file to git -- so `node_modules/`,
which matches a directory, does not match it and `git add -A` stages it.

Structural: the pattern is read from the file rather than exercised, because
`git check-ignore` cannot tell a directory pattern from a file one without the
path existing, and planting a link to find out would mutate the tree.
"""

from __future__ import annotations

from tests._repo import REPO_ROOT

IGNORE = REPO_ROOT / ".gitignore"


def test_the_pattern_matches_a_link_and_not_only_a_directory() -> None:
    """The slashless twin of `node_modules/`, which is what reaches a link."""
    lines = [one.strip() for one in IGNORE.read_text(encoding="utf-8").splitlines()]
    assert "node_modules" in lines, (
        "`.gitignore` has no slashless `node_modules`, so a worktree's linked "
        "node_modules is not ignored and `git add -A` commits a link to an absolute "
        "path on one machine. It reads as a duplicate of `node_modules/` and is not: "
        "that one matches a directory only."
    )
